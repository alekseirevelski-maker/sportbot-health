# Порог → ранг. Порядок: от самого высокого к самому низкому.
# Ступени выше «Золота» добавлены после бага: серия замирала на 60 днях,
# и спортсмену с длинной серией больше ничего не доставалось.
RANKS = [
    (365, "🏛️ Бессмертный"),
    (100, "👑 Легенда"),
    (60,  "💠 Платина"),
    (30,  "🥇 Золото"),
    (14,  "🥈 Серебро"),
    (7,   "🥉 Бронза"),
    (3,   "⭐ Старт"),
]


def get_rank(streak: int) -> str:
    for threshold, name in RANKS:
        if streak >= threshold:
            return name
    return "🌱 Новичок"


def get_rank_plain(streak: int) -> str:
    """Ранг без эмодзи — для PNG-отчётов (PIL не рисует цветные эмодзи)."""
    if streak <= 0:
        return "Новичок"
    return get_rank(streak).split(" ", 1)[1]


