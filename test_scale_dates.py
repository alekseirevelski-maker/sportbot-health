"""Регресс-тест разбора дат в CSV весов (баг 12.10.2026: даты превращались в мусор).

Что было: в форматах не было форм без секунд и с секундами, поэтому реальные даты
уходили в regex-fallback и портились:
    "2026/9/16 19:30"       -> 2016-09-26   (замер пропадал из истории: год 2016)
    "09/16/2026 17:57:00"   -> 2026-16-09   (месяц 16 → история и тренд ломались)
    "10/12/2026 16:33:00"   -> 2026-12-10   (будущее → «последний замер» = старый)
Последствия для людей: виден только последний замер и перевёрнутый тренд.

Запуск: python3 test_scale_dates.py  (из каталога бота, код возврата 0 = ок)
"""
import os
import sys
from datetime import date, datetime

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from scale_csv_parser import _parse_record_datetime, parse_scale_csv_dated  # noqa: E402

# Реальные форматы экспортов MovingLife / GARLYN (взяты из логов бота 12.10.2026):
#   healthdata.csv -> "2026/10/12 16:33"     (YYYY/MM/DD ЧЧ:ММ)
#   data<N>.csv    -> "10/12/2026 16:33:00"  (MM/DD/YYYY ЧЧ:ММ:СС)
EXACT = {
    "2026/10/12 16:33": "2026-10-12",
    "2026/9/16 19:30": "2026-09-16",
    "2026/8/26 17:00": "2026-08-26",
    "2026/10/12 16:33:00": "2026-10-12",
    "2026/9/16 19:30:00": "2026-09-16",
    "10/12/2026 16:33:00": "2026-10-12",
    "09/16/2026 17:57:00": "2026-09-16",
    "08/26/2026 11:42:00": "2026-08-26",
    "2026-10-12 11:42:17": "2026-10-12",
    "2026.10.12 16:33": "2026-10-12",
    "12.10.2026 16:33": "2026-10-12",
    "16.09.2026 17:57": "2026-09-16",
    "26.08.2026 11:42": "2026-08-26",
    "2026/16/09 17:57": "2026-09-16",   # день перед месяцем
    "2026/26/08 11:42": "2026-08-26",
}

CSV_A = "\n".join([
    "Date,ИМТ,Вес,Безж. мас. Тела,Масса жира(%),Вода в организме(%),Мышцы(%),Кости,BMR,AMR",
    '"2026/10/12 16:33",23.4,74.20кг,57.2кг,22.9%,56.5%,71.8%,3.2кг,1606kcal,2120kcal',
    '"2026/9/16 19:30",22.7,71.95кг,56.5кг,21.6%,56.9%,72.1%,3.0кг,1560kcal,2060kcal',
    '"2026/8/26 17:00",22.2,70.40кг,55.0кг,21.0%,57.0%,71.0%,2.9кг,1520kcal,2000kcal',
])

CSV_B_HEADER = ('"date","Вес","Масса жира(%)","Мышцы(%)","Белок %","Кости(%)","ИМТ","BMR",'
                '"Вода в организме(%)","Безж. мас. Тела","AMR","Подкожный жир",'
                '"Cкелетные мыщцы(%)","Индекс висцерального жира","Тип телосложения"')
CSV_B = "\n".join([
    CSV_B_HEADER,
    '"10/12/2026 16:35:00","61.35кг","19.0%","71.5%","17.0%","3.0%",20.5,"1450kcal","56.0%","49.0кг","1900kcal","12.0%","35.0%",3,"Спортсмен"',
    '"09/16/2026 17:57:00","60.70кг","19.3%","71.0%","17.0%","3.0%",20.2,"1430kcal","55.8%","48.5кг","1880kcal","12.3%","34.5%",3,"Спортсмен"',
    '"08/26/2026 11:42:00","59.90кг","17.4%","72.0%","17.2%","2.9%",20.0,"1410kcal","56.2%","49.5кг","1860kcal","11.0%","35.5%",3,"Спортсмен"',
])

EXPECTED_ORDER = ["2026-08-26", "2026-09-16", "2026-10-12"]


def main():
    fails = []

    for raw, exp in EXACT.items():
        got, _ = _parse_record_datetime(raw)
        if got != exp:
            fails.append(f"дата {raw!r}: получили {got}, ждали {exp}")

    # любого мусора быть не должно: месяц ≤ 12, год текущий, не из будущего
    for raw in list(EXACT) + ["2026/12/10 16:33", "2026-16-09", "2026-26-08"]:
        got, _ = _parse_record_datetime(raw)
        if not got:
            continue
        y, m, _d = (int(x) for x in got.split("-"))
        if m < 1 or m > 12:
            fails.append(f"{raw!r} -> месяц {m}")
        if y < date.today().year - 1:
            fails.append(f"{raw!r} -> год {y} (замер уедет из истории)")

    # полные файлы обоих вариантов: даты по возрастанию, значения на месте
    for label, content, fname, need_visceral in (
        ("A healthdata.csv", CSV_A, "healthdata.csv", False),
        ("B data*.csv", CSV_B, "data20261012164158.csv", True),
    ):
        recs = sorted(parse_scale_csv_dated(content, fname), key=lambda r: r.get("record_date") or "")
        got_dates = [r.get("record_date") for r in recs]
        if got_dates != EXPECTED_ORDER:
            fails.append(f"CSV {label}: даты {got_dates}, ждали {EXPECTED_ORDER}")
        if any(r.get("weight_kg") is None for r in recs):
            fails.append(f"CSV {label}: потерян вес")
        if need_visceral and any(r.get("visceral_fat_index") is None for r in recs):
            fails.append(f"CSV {label}: потерян висцеральный жир (маппинг колонок)")

    if fails:
        print("ПРОВАЛ:")
        for f in fails:
            print("  -", f)
        return 1
    print(f"OK: дат проверено {len(EXACT)}, оба варианта CSV разобраны верно "
          f"({datetime.now().strftime('%d.%m.%Y %H:%M')})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
